# Cache
# ---------------------------------------------------------------------------

def compute_binary_hash(binary_path: str) -> str:
    digest = hashlib.sha256()
    with open(binary_path, "rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _load_cache_index() -> dict:
    try:
        with open(CACHE_INDEX, "r", encoding="utf-8") as stream:
            data = json.load(stream)
            return data if isinstance(data, dict) else {}
    except (FileNotFoundError, json.JSONDecodeError, OSError):
        return {}


def _save_cache_index(index: dict) -> None:
    os.makedirs(CACHE_DIR, exist_ok=True)
    temp = CACHE_INDEX + ".tmp"
    with open(temp, "w", encoding="utf-8") as stream:
        json.dump(index, stream, indent=2, ensure_ascii=False)
    os.replace(temp, CACHE_INDEX)


def _cache_key(binary_hash: str, revng_version: str, clang_version: str) -> str:
    raw = f"{binary_hash}|{PIPELINE_VERSION}|{revng_version}|{clang_version}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def _artifacts_from_dict(data: dict) -> RecoveryArtifacts:
    allowed = RecoveryArtifacts.__dataclass_fields__.keys()
    return RecoveryArtifacts(**{key: value for key, value in data.items() if key in allowed})


def _cache_artifacts_valid(artifacts: RecoveryArtifacts) -> bool:
    required = [
        artifacts.runtime_root_bc,
        artifacts.runtime_root_ll,
        artifacts.runtime_executable,
        artifacts.cleanup_bc,
        artifacts.cleanup_ll,
        artifacts.native_bc,
        artifacts.native_ll,
        artifacts.native_object,
        artifacts.translated_executable,
        artifacts.manifest_path,
    ]
    return artifacts.success and all(path and os.path.exists(path) for path in required)


def list_cache_entries() -> None:
    index = _load_cache_index()
    if not index:
        print(f"{Color.YELLOW}[!] Cache trống.{Color.END}")
        return
    for key, value in index.items():
        print(f"{Color.GRAY}{key}{Color.END}")
        print(f"  binary: {value.get('binary_path')}")
        print(f"  runtime_root_ll: {value.get('runtime_root_ll')}")
        print(f"  native_ll: {value.get('native_ll')}")
        print(f"  translated_executable: {value.get('translated_executable')}")
        print(f"  timestamp: {value.get('timestamp')}")


def clear_cache() -> None:
    if os.path.isdir(CACHE_DIR):
        shutil.rmtree(CACHE_DIR)
    print(f"{Color.GREEN}[✓] Đã xóa cache.{Color.END}")


# ---------------------------------------------------------------------------
# Manifest
# ---------------------------------------------------------------------------

def _write_manifest(artifacts: RecoveryArtifacts) -> None:
    if not artifacts.manifest_path:
        return
    manifest = {
        "pipeline_version": PIPELINE_VERSION,
        "binary": artifacts.binary_path,
        "representations": {
            "runtime_root_ir": {
                "bitcode": artifacts.runtime_root_bc,
                "llvm_ir": artifacts.runtime_root_ll,
                "purpose": "rev.ng runtime-oriented IR",
                "standalone_clang_linkable": False,
                "recompile_route": "revng artifact recompile",
                "executable": artifacts.runtime_executable,
            },
            "cleanup_ir": {
                "bitcode": artifacts.cleanup_bc,
                "llvm_ir": artifacts.cleanup_ll,
                "purpose": "per-function LLVM analysis IR",
                "standalone_program": False,
                "function_count": artifacts.cleanup_function_count,
            },
            "native_looking_ir": {
                "bitcode": artifacts.native_bc,
                "llvm_ir": artifacts.native_ll,
                "object": artifacts.native_object,
                "purpose": "Clang IR generated from rev.ng decompiled C",
                "object_compilable": True,
                "standalone_clang_linkable": False,
                "reason": (
                    "The module may not define main and may reference rev.ng/runtime "
                    "helpers or dynamically resolved binary functions."
                ),
                "function_count": artifacts.native_function_count,
            },
        },
        "semantic_reference": {
            "executable": artifacts.translated_executable,
            "producer": "revng artifact recompile-isolated",
            "scope": (
                "Differential testing validates the rev.ng runtime translation. "
                "It does not by itself prove that native-looking IR is a standalone program."
            ),
        },
    }
    with open(artifacts.manifest_path, "w", encoding="utf-8") as stream:
        json.dump(manifest, stream, indent=2, ensure_ascii=False)


