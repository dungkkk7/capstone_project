#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""rev.ng binary recovery pipeline.

This module intentionally keeps three representations separate:

1. runtime root IR (`*.runtime-root.ll`)
   - rev.ng-specific LLVM IR;
   - recompilable through rev.ng's runtime/link pipeline;
   - not expected to link directly with plain Clang.

2. cleanup IR (`*.cleanup.ll`)
   - one LLVM function per recovered binary function;
   - suitable for LLVM analyses;
   - not a standalone program.

3. native-looking IR (`*.native.ll`)
   - generated by Clang from rev.ng's recompilable C archive;
   - valid LLVM IR and compilable to an object file;
   - not assumed to contain `main` or implementations of rev.ng/runtime helpers.

The executable used for semantic differential testing is produced by
`revng artifact recompile-isolated`, because that step links the required
runtime and binary support.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from dataclasses import asdict, dataclass
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tarfile
import time
from typing import Optional, Sequence

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, "../.."))
REVNG_DIR = os.path.join(PROJECT_ROOT, "dependency", "revng")
CACHE_DIR = os.path.join(PROJECT_ROOT, "result", ".lifting_cache_v4")
CACHE_INDEX = os.path.join(CACHE_DIR, "cache_index.json")
PIPELINE_VERSION = "revng-split-ir-v4"


class Color:
    BLUE = "\033[94m"
    GREEN = "\033[92m"
    YELLOW = "\033[93m"
    RED = "\033[91m"
    GRAY = "\033[90m"
    BOLD = "\033[1m"
    END = "\033[0m"


@dataclass
class RecoveryArtifacts:
    success: bool = False
    binary_path: Optional[str] = None
    output_dir: Optional[str] = None

    # rev.ng runtime-oriented root IR
    runtime_root_zstd: Optional[str] = None
    runtime_root_bc: Optional[str] = None
    runtime_root_ll: Optional[str] = None
    runtime_executable: Optional[str] = None

    # per-function analysis IR
    cleanup_zstd: Optional[str] = None
    cleanup_bc: Optional[str] = None
    cleanup_ll: Optional[str] = None

    # decompiled C and Clang-native-looking IR
    recompilable_archive: Optional[str] = None
    recovered_source_dir: Optional[str] = None
    recovered_c: Optional[str] = None
    native_raw_bc: Optional[str] = None
    native_bc: Optional[str] = None
    native_ll: Optional[str] = None
    native_object: Optional[str] = None

    # rev.ng executable with isolated functions + required runtime
    translated_executable: Optional[str] = None

    model_path: Optional[str] = None
    resume_dir: Optional[str] = None
    manifest_path: Optional[str] = None
    cleanup_function_count: int = 0
    native_function_count: int = 0
    error: Optional[str] = None

    def existing(self, field: str) -> Optional[str]:
        value = getattr(self, field, None)
        return value if value and os.path.exists(value) else None


# ---------------------------------------------------------------------------
# Tool and command helpers
# ---------------------------------------------------------------------------

def _is_executable(path: Optional[str]) -> bool:
    return bool(path and os.path.isfile(path) and os.access(path, os.X_OK))


def _find_revng_bin() -> Optional[str]:
    for candidate in (
        shutil.which("revng"),
        os.path.join(REVNG_DIR, "bin", "revng"),
        os.path.join(REVNG_DIR, "revng"),
    ):
        if _is_executable(candidate):
            return os.path.realpath(candidate)
    return None


def _candidate_tool_dirs(revng_bin: Optional[str]) -> list[str]:
    result: list[str] = []
    if revng_bin:
        base = os.path.dirname(os.path.realpath(revng_bin))
        result.extend(
            [
                base,
                os.path.join(base, "bin"),
                os.path.abspath(os.path.join(base, "..", "bin")),
                os.path.join(base, "root", "lib64", "llvm", "llvm", "bin"),
                os.path.abspath(
                    os.path.join(base, "..", "root", "lib64", "llvm", "llvm", "bin")
                ),
            ]
        )
    result.extend(
        [
            os.path.join(REVNG_DIR, "bin"),
            os.path.join(REVNG_DIR, "root", "lib64", "llvm", "llvm", "bin"),
        ]
    )
    seen: set[str] = set()
    unique: list[str] = []
    for directory in result:
        directory = os.path.abspath(directory)
        if directory not in seen:
            seen.add(directory)
            unique.append(directory)
    return unique


def _find_tool(revng_bin: Optional[str], names: Sequence[str]) -> Optional[str]:
    for directory in _candidate_tool_dirs(revng_bin):
        for name in names:
            candidate = os.path.join(directory, name)
            if _is_executable(candidate):
                return candidate
    for name in names:
        candidate = shutil.which(name)
        if candidate:
            return candidate
    return None


def _tool_version(tool: Optional[str]) -> str:
    if not tool:
        return "missing"
    try:
        result = subprocess.run(
            [tool, "--version"],
            capture_output=True,
            text=True,
            check=False,
            timeout=15,
        )
        text = (result.stdout or result.stderr or "unknown").strip()
        return text.splitlines()[0] if text else "unknown"
    except Exception:
        return "unknown"


def _format_cmd(cmd: Sequence[str]) -> str:
    return " ".join(shlex.quote(str(part)) for part in cmd)


def run_command(
    cmd: Sequence[str],
    label: str,
    *,
    cwd: Optional[str] = None,
    timeout: Optional[float] = None,
) -> bool:
    print(f"\n{Color.BLUE}[*] {label}{Color.END}")
    print(f"{Color.GRAY}    $ {_format_cmd(cmd)}{Color.END}")
    try:
        result = subprocess.run(
            list(cmd),
            cwd=cwd,
            capture_output=True,
            text=True,
            check=False,
            timeout=timeout,
        )
    except FileNotFoundError as exc:
        print(f"{Color.RED}[✗] Không tìm thấy lệnh: {exc}{Color.END}")
        return False
    except subprocess.TimeoutExpired:
        print(f"{Color.RED}[✗] Lệnh vượt quá timeout.{Color.END}")
        return False
    except Exception as exc:
        print(f"{Color.RED}[✗] Lỗi thực thi: {exc}{Color.END}")
        return False

    if result.returncode == 0:
        print(f"{Color.GREEN}[✓] Hoàn tất.{Color.END}")
        if result.stdout.strip():
            print(f"{Color.GRAY}{result.stdout.strip()[:2000]}{Color.END}")
        return True

    print(f"{Color.RED}[✗] Thất bại (code {result.returncode}).{Color.END}")
    if result.stdout.strip():
        print(f"{Color.GRAY}stdout: {result.stdout.strip()[:3000]}{Color.END}")
    if result.stderr.strip():
        print(f"{Color.RED}stderr: {result.stderr.strip()[:5000]}{Color.END}")
    return False


def _decompress_zstd(src: str, dst: str) -> bool:
    try:
        import zstandard as zstd  # type: ignore

        with open(src, "rb") as source, open(dst, "wb") as target:
            zstd.ZstdDecompressor().copy_stream(source, target)
        return True
    except ImportError:
        pass
    except Exception as exc:
        print(f"{Color.YELLOW}[!] Python zstandard thất bại: {exc}{Color.END}")

    zstd_bin = shutil.which("zstd")
    if not zstd_bin:
        return False
    return run_command(
        [zstd_bin, "-d", "--force", src, "-o", dst],
        "Giải nén Zstandard",
    )


def _safe_extract_tar(archive_path: str, destination: str) -> None:
    root = Path(destination).resolve()
    with tarfile.open(archive_path, "r:*") as archive:
        for member in archive.getmembers():
            target = (root / member.name).resolve()
            if target != root and root not in target.parents:
                raise RuntimeError(f"Unsafe archive member: {member.name}")
        archive.extractall(destination)


def _emit_llvm_text(
    bitcode: str,
    output_ll: str,
    llvm_dis: Optional[str],
    clang: str,
    label: str,
) -> bool:
    if llvm_dis:
        return run_command([llvm_dis, bitcode, "-o", output_ll], label)
    return run_command(
        [clang, "-S", "-emit-llvm", bitcode, "-o", output_ll],
        label + " (clang fallback)",
    )


def _count_llvm_definitions(ll_path: str) -> int:
    count = 0
    with open(ll_path, "r", encoding="utf-8", errors="replace") as stream:
        for line in stream:
            if line.lstrip().startswith("define "):
                count += 1
    return count


def _make_executable(path: str) -> bool:
    if not os.path.isfile(path):
        return False
    os.chmod(path, os.stat(path).st_mode | 0o111)
    return os.access(path, os.X_OK)


