# Core recovery pipeline
# ---------------------------------------------------------------------------

def recover_binary(
    binary_path: str,
    output_dir: Optional[str] = None,
    *,
    use_cache: bool = True,
    force_relift: bool = False,
    optimize_native_ir: bool = True,
    # Kept only for old callers. Standalone native executable is not promised.
    require_native_executable: bool = False,
) -> RecoveryArtifacts:
    binary_path = os.path.abspath(binary_path)
    if not os.path.isfile(binary_path):
        return RecoveryArtifacts(error=f"Binary không tồn tại: {binary_path}")

    if require_native_executable:
        print(
            f"{Color.YELLOW}[!] --require-native-executable không còn được hỗ trợ: "
            "native-looking IR chỉ được xác nhận compile thành object. "
            "Executable semantic dùng recompile-isolated của rev.ng."
            f"{Color.END}"
        )

    if output_dir is None:
        parent = os.path.basename(os.path.dirname(binary_path)) or "binary"
        output_dir = os.path.join(PROJECT_ROOT, "result", parent)
    output_dir = os.path.abspath(output_dir)
    os.makedirs(output_dir, exist_ok=True)

    basename = os.path.splitext(os.path.basename(binary_path))[0]
    revng = _find_revng_bin()
    if not revng:
        return RecoveryArtifacts(error="Không tìm thấy revng trong PATH hoặc dependency/revng")

    clang = _find_tool(revng, ["clang", "clang-21", "clang-20", "clang-19", "clang-18"])
    llvm_dis = _find_tool(
        revng,
        ["llvm-dis", "llvm-dis-21", "llvm-dis-20", "llvm-dis-19", "llvm-dis-18"],
    )
    opt = _find_tool(revng, ["opt", "opt-21", "opt-20", "opt-19", "opt-18"])
    if not clang:
        return RecoveryArtifacts(error="Thiếu clang tương thích")

    revng_version = _tool_version(revng)
    clang_version = _tool_version(clang)
    cache_key = _cache_key(compute_binary_hash(binary_path), revng_version, clang_version)

    if use_cache and not force_relift:
        cached_data = _load_cache_index().get(cache_key)
        if isinstance(cached_data, dict):
            cached = _artifacts_from_dict(cached_data)
            if _cache_artifacts_valid(cached):
                print(f"{Color.GREEN}[✓] Cache HIT: {binary_path}{Color.END}")
                return cached

    artifacts = RecoveryArtifacts(
        binary_path=binary_path,
        output_dir=output_dir,
        runtime_root_zstd=os.path.join(output_dir, f"{basename}.runtime-root.bc.zstd"),
        runtime_root_bc=os.path.join(output_dir, f"{basename}.runtime-root.bc"),
        runtime_root_ll=os.path.join(output_dir, f"{basename}.runtime-root.ll"),
        runtime_executable=os.path.join(output_dir, f"{basename}.runtime.translated"),
        cleanup_zstd=os.path.join(output_dir, f"{basename}.cleanup.bc.zstd"),
        cleanup_bc=os.path.join(output_dir, f"{basename}.cleanup.bc"),
        cleanup_ll=os.path.join(output_dir, f"{basename}.cleanup.ll"),
        recompilable_archive=os.path.join(output_dir, f"{basename}.recompilable.tar.gz"),
        recovered_source_dir=os.path.join(output_dir, f"{basename}.recovered-source"),
        native_raw_bc=os.path.join(output_dir, f"{basename}.native.raw.bc"),
        native_bc=os.path.join(output_dir, f"{basename}.native.bc"),
        native_ll=os.path.join(output_dir, f"{basename}.native.ll"),
        native_object=os.path.join(output_dir, f"{basename}.native.o"),
        translated_executable=os.path.join(output_dir, f"{basename}.translated"),
        model_path=os.path.join(output_dir, f"{basename}.model.yml"),
        resume_dir=os.path.join(output_dir, f"{basename}.revng-project"),
        manifest_path=os.path.join(output_dir, f"{basename}.artifacts.json"),
    )

    print(f"{Color.BLUE}[*] Binary: {binary_path}{Color.END}")
    print(f"{Color.BLUE}[*] revng: {revng}{Color.END}")
    print(f"{Color.BLUE}[*] clang: {clang}{Color.END}")
    print(f"{Color.BLUE}[*] Output: {output_dir}{Color.END}")

    # 1. Runtime-oriented root IR. This is the LLVM representation tied to the
    #    rev.ng recompile pipeline, not a native Clang application module.
    lift_cmd = [
        revng,
        "artifact",
        "--resume",
        artifacts.resume_dir,
        "--analyze",
        "--save-model",
        artifacts.model_path,
        "lift",
        binary_path,
        "-o",
        artifacts.runtime_root_zstd,
    ]
    if not run_command(lift_cmd, "1/11 binary → rev.ng runtime root IR"):
        artifacts.error = "revng lift thất bại"
        return artifacts
    if not _decompress_zstd(artifacts.runtime_root_zstd, artifacts.runtime_root_bc):
        artifacts.error = "Không giải nén được runtime root IR"
        return artifacts
    if not _emit_llvm_text(
        artifacts.runtime_root_bc,
        artifacts.runtime_root_ll,
        llvm_dis,
        clang,
        "2/11 runtime root bitcode → runtime-root.ll",
    ):
        artifacts.error = "Không xuất được runtime-root.ll"
        return artifacts

    # 2. Recompile directly from the root path with the runtime.
    recompile_cmd = [
        revng,
        "artifact",
        "--resume",
        artifacts.resume_dir,
        "recompile",
        binary_path,
        "-o",
        artifacts.runtime_executable,
    ]
    if not run_command(recompile_cmd, "3/11 rev.ng root IR → runtime executable"):
        artifacts.error = "revng recompile thất bại"
        return artifacts
    if not _make_executable(artifacts.runtime_executable):
        artifacts.error = "Runtime executable không có quyền execute"
        return artifacts

    # 3. Cleanup analysis IR.
    cleanup_cmd = [
        revng,
        "artifact",
        "--resume",
        artifacts.resume_dir,
        "cleanup-ir",
        binary_path,
        "-o",
        artifacts.cleanup_zstd,
    ]
    if not run_command(cleanup_cmd, "4/11 binary → cleanup-ir"):
        artifacts.error = "revng cleanup-ir thất bại"
        return artifacts
    if not _decompress_zstd(artifacts.cleanup_zstd, artifacts.cleanup_bc):
        artifacts.error = "Không giải nén được cleanup-ir"
        return artifacts
    if not _emit_llvm_text(
        artifacts.cleanup_bc,
        artifacts.cleanup_ll,
        llvm_dis,
        clang,
        "5/11 cleanup bitcode → cleanup.ll",
    ):
        artifacts.error = "Không xuất được cleanup.ll"
        return artifacts
    artifacts.cleanup_function_count = _count_llvm_definitions(artifacts.cleanup_ll)
    if artifacts.cleanup_function_count == 0:
        artifacts.error = "cleanup-ir không chứa function definition"
        return artifacts

    # 4. Isolated translated executable used as semantic reference.
    isolated_cmd = [
        revng,
        "artifact",
        "--resume",
        artifacts.resume_dir,
        "recompile-isolated",
        binary_path,
        "-o",
        artifacts.translated_executable,
    ]
    if not run_command(isolated_cmd, "6/11 tạo recompile-isolated executable"):
        artifacts.error = "recompile-isolated thất bại"
        return artifacts
    if not _make_executable(artifacts.translated_executable):
        artifacts.error = "Translated executable không có quyền execute"
        return artifacts

    # 5. Decompiled C → native-looking Clang IR. This lane is verified only up
    #    to object generation; it is not linked as a standalone application.
    archive_cmd = [
        revng,
        "artifact",
        "--resume",
        artifacts.resume_dir,
        "emit-recompilable-archive",
        binary_path,
        "-o",
        artifacts.recompilable_archive,
    ]
    if not run_command(archive_cmd, "7/11 xuất recompilable C archive"):
        artifacts.error = "emit-recompilable-archive thất bại"
        return artifacts

    try:
        if os.path.isdir(artifacts.recovered_source_dir):
            shutil.rmtree(artifacts.recovered_source_dir)
        os.makedirs(artifacts.recovered_source_dir, exist_ok=True)
        _safe_extract_tar(artifacts.recompilable_archive, artifacts.recovered_source_dir)
    except Exception as exc:
        artifacts.error = f"Không giải nén được recompilable archive: {exc}"
        return artifacts

    candidates = sorted(Path(artifacts.recovered_source_dir).rglob("functions.c"))
    if not candidates:
        artifacts.error = "Archive không chứa functions.c"
        return artifacts
    artifacts.recovered_c = str(candidates[0].resolve())
    source_dir = str(candidates[0].parent.resolve())

    include_dirs = sorted({source_dir, artifacts.recovered_source_dir})
    common_c_flags = [
        "-std=gnu11",
        "-O0",
        "-Xclang",
        "-disable-O0-optnone",
        "-fno-discard-value-names",
        "-fno-strict-aliasing",
        "-fwrapv",
        "-Wno-everything",
    ]
    for include_dir in include_dirs:
        common_c_flags.extend(["-I", include_dir])

    compile_bc_cmd = [
        clang,
        *common_c_flags,
        "-emit-llvm",
        "-c",
        artifacts.recovered_c,
        "-o",
        artifacts.native_raw_bc,
    ]
    if not run_command(compile_bc_cmd, "8/11 recovered C → native-looking bitcode"):
        artifacts.error = "Clang không compile được recovered C sang bitcode"
        return artifacts

    if optimize_native_ir and opt:
        if not run_command(
            [opt, "-passes=default<O1>", artifacts.native_raw_bc, "-o", artifacts.native_bc],
            "9/11 tối ưu nhẹ native-looking IR",
        ):
            print(f"{Color.YELLOW}[!] opt thất bại; dùng raw Clang bitcode.{Color.END}")
            shutil.copy2(artifacts.native_raw_bc, artifacts.native_bc)
    else:
        shutil.copy2(artifacts.native_raw_bc, artifacts.native_bc)

    if not _emit_llvm_text(
        artifacts.native_bc,
        artifacts.native_ll,
        llvm_dis,
        clang,
        "10/11 native bitcode → native.ll",
    ):
        artifacts.error = "Không xuất được native.ll"
        return artifacts
    artifacts.native_function_count = _count_llvm_definitions(artifacts.native_ll)

    if not run_command(
        [clang, "-c", artifacts.native_bc, "-o", artifacts.native_object],
        "11/11 xác nhận native-looking IR compile thành object",
    ):
        artifacts.error = "Native-looking IR không compile được thành object"
        return artifacts

    artifacts.success = True
    artifacts.error = None
    _write_manifest(artifacts)

    if use_cache:
        index = _load_cache_index()
        cache_data = asdict(artifacts)
        cache_data["timestamp"] = time.strftime("%Y-%m-%dT%H:%M:%S")
        cache_data["pipeline_version"] = PIPELINE_VERSION
        cache_data["revng_version"] = revng_version
        cache_data["clang_version"] = clang_version
        index[cache_key] = cache_data
        _save_cache_index(index)

    print(f"\n{Color.GREEN}[✓] Recovery hoàn tất.{Color.END}")
    print(f"    runtime root IR:  {artifacts.runtime_root_ll}")
    print(f"    runtime exe:      {artifacts.runtime_executable}")
    print(f"    cleanup IR:       {artifacts.cleanup_ll}")
    print(f"    native-looking IR:{artifacts.native_ll}")
    print(f"    native object:    {artifacts.native_object}")
    print(f"    semantic exe:     {artifacts.translated_executable}")
    print(f"    manifest:         {artifacts.manifest_path}")
    print(
        f"{Color.YELLOW}[!] native-looking IR được xác nhận tới object file; "
        "không link thẳng bằng Clang vì có thể thiếu main/runtime helpers."
        f"{Color.END}"
    )
    return artifacts


def _copy_requested_output(artifacts: RecoveryArtifacts, output: str) -> bool:
    output = os.path.abspath(output)
    os.makedirs(os.path.dirname(output), exist_ok=True)
    lower = output.lower()

    if lower.endswith(".runtime.ll"):
        source = artifacts.runtime_root_ll
    elif lower.endswith(".runtime.bc"):
        source = artifacts.runtime_root_bc
    elif lower.endswith(".cleanup.ll"):
        source = artifacts.cleanup_ll
    elif lower.endswith(".cleanup.bc"):
        source = artifacts.cleanup_bc
    elif lower.endswith(".ll"):
        source = artifacts.native_ll
    elif lower.endswith(".bc"):
        source = artifacts.native_bc
    elif lower.endswith((".exe", ".out", ".bin")):
        # Executable outputs are always the runtime-linked rev.ng translation.
        source = artifacts.translated_executable
    elif lower.endswith(".json"):
        source = artifacts.manifest_path
    else:
        print(
            f"{Color.RED}[✗] --output phải là .ll/.bc/.runtime.ll/.runtime.bc/"
            f".cleanup.ll/.cleanup.bc/.exe/.out/.bin/.json.{Color.END}"
        )
        return False

    if not source or not os.path.isfile(source):
        print(f"{Color.RED}[✗] Artifact yêu cầu chưa được tạo: {source}{Color.END}")
        return False
    if os.path.abspath(source) != output:
        shutil.copy2(source, output)
    if lower.endswith((".exe", ".out", ".bin")):
        _make_executable(output)
    return True


def lift_binary(
    binary_path: str,
    output: Optional[str] = None,
    arch: str = "amd64",
    os_name: str = "linux",
    entrypoint: str = "main",
    use_cache: bool = True,
    force_relift: bool = False,
    disassembler: Optional[str] = None,
    ghidra: Optional[str] = None,
) -> bool:
    """Backward-compatible boolean wrapper.

    `arch`, `os_name`, `entrypoint`, `disassembler`, and `ghidra` are retained
    for old call sites only. rev.ng derives architecture/ABI/entry point from
    the input binary and model.
    """
    del arch, os_name, entrypoint, disassembler, ghidra
    output_dir = os.path.dirname(os.path.abspath(output)) if output else None
    artifacts = recover_binary(
        binary_path,
        output_dir,
        use_cache=use_cache,
        force_relift=force_relift,
    )
    if not artifacts.success:
        print(f"{Color.RED}[✗] Recovery thất bại: {artifacts.error}{Color.END}")
        return False
    return _copy_requested_output(artifacts, output) if output else True


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "binary → runtime rev.ng IR/executable + cleanup IR + native-looking object IR"
        )
    )
    parser.add_argument("-b", "--binary", help="Binary đầu vào")
    parser.add_argument("-o", "--output", help="Copy một artifact ra đường dẫn chỉ định")
    parser.add_argument("--output-dir", help="Thư mục chứa toàn bộ artifact")
    parser.add_argument("--no-opt", action="store_true", help="Không chạy opt O1 cho native IR")
    parser.add_argument("--no-cache", action="store_true")
    parser.add_argument("--force-relift", action="store_true")
    parser.add_argument("--list-cache", action="store_true")
    parser.add_argument("--clear-cache", action="store_true")
    # Accepted for compatibility but intentionally not enforced.
    parser.add_argument("--require-native-exe", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args()

    if args.list_cache:
        list_cache_entries()
        return 0
    if args.clear_cache:
        clear_cache()
        return 0
    if not args.binary:
        parser.error("--binary là bắt buộc")

    output_dir = args.output_dir
    if not output_dir and args.output:
        output_dir = os.path.dirname(os.path.abspath(args.output))

    artifacts = recover_binary(
        args.binary,
        output_dir,
        use_cache=not args.no_cache,
        force_relift=args.force_relift,
        optimize_native_ir=not args.no_opt,
        require_native_executable=args.require_native_exe,
    )
    if not artifacts.success:
        print(f"{Color.RED}[✗] {artifacts.error}{Color.END}")
        return 1
    if args.output and not _copy_requested_output(artifacts, args.output):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
